#!/usr/bin/env python3
"""Create a new Insland project skeleton.

Usage:
    py scripts/new_project.py my_game
    py scripts/new_project.py "Space Game" --force

The generated directory lives under ``projects/<name>`` and contains a
``main.cpp`` built on ``insland::Application``, a ``CMakeLists.txt`` and an
empty ``assets`` folder.  The root CMake build picks up every project that has
a CMakeLists.txt automatically, so no manual registration is required.

In Visual Studio Code the same thing is available without a terminal:
**Terminal > Run Task > Insland: New Project** (it asks for the name, then
reconfigures and builds).
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PROJECTS = ROOT / "projects"

MAIN_TEMPLATE = r"""// ---------------------------------------------------------------------------
// @TITLE@ - an Insland Engine project
// ---------------------------------------------------------------------------
// Generated by scripts/new_project.py.  Build with the VS Code CMake buttons,
// or from a terminal:
//
//     cmake --build --preset windows-d3d11 --target Insland_@TARGET@
//     ./build/Insland@CLASS@
//
// Controls: left-drag orbits, wheel zooms, Escape quits.
// ---------------------------------------------------------------------------

#include "insland/insland.hpp"
#include "imgui.h"

using namespace insland;

int main()
{
    Application app("@TITLE@");
    Engine& engine = app.engine();
    World world;
    UI ui;

    float yaw = 35.0f, pitch = 22.0f, distance = 52.0f;
    const Vec3 center{0.0f, 8.0f, 0.0f};

    AppCallbacks cb;
    cb.on_start = [&] {
        engine.set_sky_enabled(true);
        world.generate(engine);
        ui.init(*engine.renderer());
    };

    cb.on_update = [&](float dt) {
        if (input::key_pressed(input::Key::Escape)) app.quit();

        // Camera: left-drag orbits, wheel zooms.
        if (!ui.initialized() || !ui.wants_mouse())
        {
            if (input::mouse_down(input::MouseButton::Left))
            {
                yaw += input::mouse.delta_x * 0.35f;
                pitch -= input::mouse.delta_y * 0.35f;
            }
            distance = clampf(distance - input::mouse.wheel * 0.6f, 2.0f, 400.0f);
        }
        pitch = clampf(pitch, -80.0f, 80.0f);
        engine.camera().orbit(yaw, pitch, distance, center);

        // Scene: the island plus a cube you can replace with your own content.
        world.draw(engine);
        engine.draw_cube(Transform{});

        // Inspector.
        if (ui.initialized())
        {
            ui.begin_frame(app.config().width, app.config().height, dt);
            ImGui::Begin("@TITLE@");
            ImGui::Text("%.0f fps", dt > 0.0f ? 1.0f / dt : 0.0f);
            ImGui::TextUnformatted(Memory::summary().c_str());
            ImGui::End();
            ui.end_frame(*engine.renderer());
        }
    };

    cb.on_shutdown = [&] { ui.shutdown(); };
    app.set_callbacks(cb);

    return app.init() ? app.run() : 1;
}
"""

CMAKE_TEMPLATE = """# @TITLE@ - generated by scripts/new_project.py

if(ANDROID)
    add_library(Insland_@TARGET@ SHARED main.cpp)
else()
    add_executable(Insland_@TARGET@ main.cpp)
endif()

target_link_libraries(Insland_@TARGET@ PRIVATE insland)

if(WIN32)
    set_target_properties(Insland_@TARGET@ PROPERTIES OUTPUT_NAME "Insland@CLASS@")
endif()
"""


def target_name(name: str) -> str:
    return re.sub(r"[^A-Za-z0-9_]", "_", name)


def class_name(name: str) -> str:
    parts = re.split(r"[^A-Za-z0-9]+", name)
    return "".join(part[:1].upper() + part[1:] for part in parts if part) or "Project"


def main() -> int:
    parser = argparse.ArgumentParser(description="Create a new Insland project.")
    parser.add_argument("name", help="project name (letters, digits, - and _)")
    parser.add_argument(
        "--force",
        action="store_true",
        help="overwrite an existing project directory",
    )
    args = parser.parse_args()

    name = args.name.strip()
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9 _-]*", name):
        print(f"error: invalid project name {name!r}", file=sys.stderr)
        return 2

    directory = PROJECTS / name
    if directory.exists() and not args.force:
        print(f"error: {directory} already exists (use --force)", file=sys.stderr)
        return 3

    directory.mkdir(parents=True, exist_ok=True)
    (directory / "assets").mkdir(exist_ok=True)

    replacements = {
        "@TITLE@": name,
        "@TARGET@": target_name(name),
        "@CLASS@": class_name(name),
    }

    def render(template: str) -> str:
        for key, value in replacements.items():
            template = template.replace(key, value)
        return template

    (directory / "main.cpp").write_text(render(MAIN_TEMPLATE), encoding="utf-8")
    (directory / "CMakeLists.txt").write_text(render(CMAKE_TEMPLATE), encoding="utf-8")
    (directory / "assets" / ".gitkeep").write_text("", encoding="utf-8")

    print(f"Created {directory.relative_to(ROOT)}")
    print("Next steps:")
    print("  - VS Code: press Build (or run the task 'Insland: New Project' next time)")
    print(f"  - terminal: cmake --build --preset windows-d3d11 --target Insland_{target_name(name)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
